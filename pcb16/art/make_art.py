#!/usr/bin/env python3
"""v1.6 art pipeline: PNG -> monochrome rectangle list on F.SilkS.

Each image is thresholded to ink, snapped to a grid, merged into the
fewest possible axis-aligned rectangles (each becomes one gr_poly).
Output: art/art_polys.py — CHECKBOX_RECTS / SAD_RECTS lists of
(x, y, w, h) in mm at board coordinates, consumed by gen_pcb.py.

Usage:  python3 art/make_art.py
"""
from PIL import Image
import numpy as np
from pathlib import Path

HERE = Path(__file__).resolve().parent

# ---------------------------------------------------------------- layout
# Placement boxes found with the free-space scan (pads/vias/drills/
# courtyards/silk excluded; silk over buried tracks is allowed).
CHECKBOX = dict(png="not_a_robot.png", org=(88.0, 1.5), w_mm=38.0,
                cell=0.24)                      # ~13 mm tall result
SAD = dict(png="sad_page.png", org=(46.0, 61.5), w_mm=14.0, h_mm=17.5)


def ink_bool(png):
    im = np.array(Image.open(png).convert("L")) < 128
    ys, xs = np.where(im)
    return im[ys.min():ys.max() + 1, xs.min():xs.max() + 1]


def best_grid(ink, lo=6, hi=20):
    """Find the native pixel-art block size: try decimating by n and
    measure reconstruction error."""
    h, w = ink.shape
    best = (None, 1e9)
    for n in range(lo, hi + 1):
        gh, gw = h // n, w // n
        if gh < 6 or gw < 6:
            continue
        g = ink[:gh * n, :gw * n].reshape(gh, n, gw, n).mean((1, 3)) > 0.5
        back = np.repeat(np.repeat(g, n, 0), n, 1)
        err = (back != ink[:gh * n, :gw * n]).mean()
        if err < best[1]:
            best = (n, err, g)
    return best


def to_grid(ink, cell_mm, w_mm):
    """Resize ink to a boolean grid where one cell = cell_mm."""
    h, w = ink.shape
    gw = max(1, round(w_mm / cell_mm))
    gh = max(1, round(gw * h / w))
    im = Image.fromarray((ink * 255).astype(np.uint8)).resize(
        (gw, gh), Image.BOX)
    return np.array(im) > 127


def merge_rects(g):
    """Greedy maximal-rectangle decomposition of a boolean grid."""
    g = g.copy()
    rects = []
    gh, gw = g.shape
    for y in range(gh):
        for x in range(gw):
            if not g[y, x]:
                continue
            w = 0
            while x + w < gw and g[y, x + w]:
                w += 1
            h = 1
            while y + h < gh and g[y + h, x:x + w].all():
                h += 1
            g[y:y + h, x:x + w] = False
            rects.append((x, y, w, h))
    return rects


def convert_checkbox():
    ink = ink_bool(HERE / CHECKBOX["png"])
    g = to_grid(ink, CHECKBOX["cell"], CHECKBOX["w_mm"])
    gh, gw = g.shape
    ox, oy = CHECKBOX["org"]
    cell = CHECKBOX["cell"]
    rects = [(ox + x * cell, oy + y * cell, w * cell, h * cell)
             for x, y, w, h in merge_rects(g)]
    return rects, g


def convert_sad():
    ink = ink_bool(HERE / SAD["png"])
    n, err, g = best_grid(ink)
    # snap to the native grid; then size cells to the placement box
    ox, oy = SAD["org"]
    gh, gw = g.shape
    cw = SAD["w_mm"] / gw
    ch = SAD["h_mm"] / gh
    c = min(cw, ch)          # keep square cells -> pixel look
    rects = [(ox + x * c, oy + y * c, w * c, h * c)
             for x, y, w, h in merge_rects(g)]
    return rects, g, (n, err)


def preview(name, g):
    for row in g:
        print(name + " |" + "".join("#" if c else "." for c in row) + "|")


if __name__ == "__main__":
    cb, gcb = convert_checkbox()
    sd, gsd, info = convert_sad()
    print(f"checkbox: grid {gcb.shape[::-1]} -> {len(cb)} rects")
    preview("cb", gcb)
    print(f"sad: native block ~{info[0]}px err {info[1]:.3f}, "
          f"grid {gsd.shape[::-1]} -> {len(sd)} rects")
    preview("sd", gsd)
    out = HERE / "art_polys.py"
    with open(out, "w") as f:
        f.write("# generated by art/make_art.py — do not edit\n")
        f.write(f"CHECKBOX_RECTS = {cb!r}\n")
        f.write(f"SAD_RECTS = {sd!r}\n")
    print("wrote", out)
