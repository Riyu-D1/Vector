"""toolchg/check/build_mjcf_stl.py - build the D10 MuJoCo scene from STL.

toolchg/mjcf_tc/build_tc.py loads each part's .step through trimesh,
which needs the 'cascadio' STEP backend - absent in the sim venv (and
installs are not allowed).  This helper imports build_tc unchanged and
replaces only its mesh() loader: same part set, same XML, geometry from
the STLs generated by toolchg/build_toolchg.py and cad/arm2b/build_arm2b.py.

Run:  python3 toolchg/check/build_mjcf_stl.py
"""
import os, sys
import trimesh

HERE = os.path.dirname(os.path.abspath(__file__))
TC = os.path.dirname(HERE)
ROOT = os.path.dirname(TC)
sys.path.insert(0, os.path.join(TC, "mjcf_tc"))
sys.path.insert(0, os.path.join(ROOT, "software", "robot-os"))

import build_tc  # noqa: E402

def mesh_stl(p):
    if p.startswith(("tc_", "tool_")):
        f = os.path.join(TC, "out", p + ".stl")
    else:
        f = os.path.join(ROOT, "cad", "arm2b", "out", p + ".stl")
    return trimesh.load(f, force="mesh")

build_tc.mesh = mesh_stl  # script body runs at import; no main()
